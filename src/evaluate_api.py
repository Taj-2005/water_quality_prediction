"""Shared interface every member codes against.

This is the contract: no module loads the dataset, builds a split, or defines a
metric on its own. If two members call ``get_splits()`` and get different data,
that is a bug to fix before any result is reported.

Owner: Parthraj Singh Bhati.
Downstream implementations land in:
  - src/clean.py (Taj) -> data/processed/clean.csv
  - src/split.py & src/preprocess.py (Parth) -> data/splits/
  - src/metrics.py (Satya) -> evaluation metrics
"""

from __future__ import annotations

import warnings
from collections.abc import Sequence
from pathlib import Path

import pandas as pd
from pandas.api.types import is_datetime64_any_dtype

from src.config import CLEAN_CSV, CLEAN_PARQUET


def _restore_dtypes(df: pd.DataFrame) -> pd.DataFrame:
    """Give a CSV-loaded frame the dtypes the parquet file carries.

    CSV stores no type information, so a fallback read returns dates as strings and
    flags as the literal text "True"/"False". Code written against the parquet path
    then fails in confusing ways - ``.dt`` on a string column, for instance. Restoring
    the dtypes here makes the two paths interchangeable, which is the only thing that
    makes a fallback safe.
    """
    from src.clean import CATEGORICALS

    if "Date_parsed" in df.columns and not is_datetime64_any_dtype(df["Date_parsed"]):
        df["Date_parsed"] = pd.to_datetime(df["Date_parsed"], errors="coerce")

    for col in CATEGORICALS + ["Area"]:
        if col in df.columns and not isinstance(df[col].dtype, pd.CategoricalDtype):
            df[col] = df[col].astype("category")

    for col in df.columns:
        if col.startswith("flag_") or col.endswith("__imputed_upstream"):
            if df[col].dtype == object:
                df[col] = df[col].map({"True": True, "False": False}).astype(bool)
            else:
                df[col] = df[col].astype(bool)

    if "n_imputed_upstream" in df.columns:
        df["n_imputed_upstream"] = df["n_imputed_upstream"].astype("int8")

    return df


def load_data(path: Path | str | None = None) -> pd.DataFrame:
    """Load the project dataset.

    Returns the cleaned, documented table produced by ``src/clean.py``.
    No imputation or scaling happens here — those belong to the preprocessing
    pipeline (src/preprocess.py), which is fitted on the training split only.

    Prefers ``data/processed/clean.parquet``, which is committed to the repository
    (45 MB) so that every member loads identical bytes rather than relying on each
    person's rerun. Falls back to ``clean.csv`` when the parquet file is absent.

    Parameters
    ----------
    path : Path | str | None, optional
        Explicit path to a cleaned table (.parquet or .csv). Defaults to the
        committed parquet, then the local CSV.

    Returns
    -------
    pd.DataFrame
        Cleaned dataset ready for splitting and pipeline transformation.

    Raises
    ------
    FileNotFoundError
        If ``data/processed/clean.csv`` has not yet been generated by Taj's
        cleaning pipeline (src/clean.py).
    """
    if path is not None:
        target = Path(path)
    elif CLEAN_PARQUET.exists():
        target = CLEAN_PARQUET
    else:
        target = CLEAN_CSV

    if not target.exists():
        raise FileNotFoundError(
            f"Cleaned dataset not found at '{target}'. The parquet file is committed, "
            "so a fresh clone should already have it - run 'git lfs install' and "
            "'git pull'. To regenerate it from the raw data instead, run "
            "'python -m src.clean'."
        )
    if target.suffix != ".parquet":
        return _restore_dtypes(pd.read_csv(target, low_memory=False))

    try:
        return pd.read_parquet(target)
    except ImportError as exc:
        # The environment has no parquet engine. This is almost always a Jupyter kernel
        # pointing at the wrong interpreter rather than a missing install, so say so.
        if path is None and CLEAN_CSV.exists():
            warnings.warn(
                f"No parquet engine available, falling back to {CLEAN_CSV.name}. "
                "Install pyarrow (pip install -r requirements.txt) and select the "
                "project .venv as your kernel to use the faster parquet path.",
                RuntimeWarning,
                stacklevel=2,
            )
            return _restore_dtypes(pd.read_csv(CLEAN_CSV, low_memory=False))
        raise ImportError(
            "Reading clean.parquet needs a parquet engine (pyarrow), and this "
            "environment has none.\n"
            "  1. Install the project requirements INTO THE ENVIRONMENT THAT RUNS THIS "
            "CODE:  pip install -r requirements.txt\n"
            "  2. In Jupyter or VS Code, check the kernel: it must be the project "
            "'.venv', not a global interpreter. VS Code: Select Kernel -> Python "
            "Environments -> .venv\n"
            "  3. Or regenerate the CSV instead:  python -m src.clean"
        ) from exc


def get_splits(
    splits_dir: Path | str | None = None,
    include_metadata: bool = True,
    include_imputation_flags: bool = False,
    scale_numeric: bool = False,
    partial_scenario: str | Sequence[str] | None = None,
) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame, pd.Series, pd.Series, pd.Series]:
    """Return the shared, seeded train/validation/test split.

    Uses Area-based site grouping to guarantee zero spatial leakage across partitions.
    Preprocessing is fitted strictly on the training partition.

    Parameters
    ----------
    splits_dir : Path | str | None, optional
        Custom directory containing splits.parquet. Defaults to data/splits/.
    include_metadata : bool, default True
        Whether to include non-chemical metadata covariates (Country, Waterbody Type).
    include_imputation_flags : bool, default False
        Whether to include upstream imputation indicator flags (reserved for Jivit's ablation).
    scale_numeric : bool, default False
        Whether to z-score normalize numeric measurements using train statistics.
    partial_scenario : str | Sequence[str] | None, optional
        Partial measurement scenario ('8/8', '7/8', '6/8', '4/8' or custom measurement list).

    Returns
    -------
    tuple
        ``(X_train, X_val, X_test, y_train, y_val, y_test)``
    """
    from src.preprocess import get_preprocessed_splits

    return get_preprocessed_splits(
        splits_dir=splits_dir,
        include_metadata=include_metadata,
        include_imputation_flags=include_imputation_flags,
        scale_numeric=scale_numeric,
        partial_scenario=partial_scenario,
    )


def evaluate(y_true, y_pred) -> dict[str, float]:
    """Evaluate predictions using the project's agreed metrics.

    Final metric implementations will be provided in ``src/metrics.py`` (Satya)
    after the baseline and evaluation protocols are established.

    Parameters
    ----------
    y_true : array-like of shape (n_samples,)
        Ground-truth target values (continuous CCME_Values for regression).
    y_pred : array-like of shape (n_samples,)
        Model predictions.

    Returns
    -------
    dict[str, float]
        Dictionary of metric names mapped to their float values (e.g.,
        {'mae': ..., 'rmse': ..., 'r2': ...}), ready for logging to CSV in results/.

    See Also
    --------
    src.metrics.ceiling_split_metrics : the same metrics reported separately for
        records at the index ceiling and below it. 35.92% of the target sits at
        exactly 100, so a pooled figure answers two questions at once.
    """
    from src.metrics import regression_metrics

    return regression_metrics(y_true, y_pred)
