"""Shared interface every member codes against.

This is the contract: no module loads the dataset, builds a split, or defines a
metric on its own. If two members call ``get_splits()`` and get different data,
that is a bug to fix before any result is reported.

Owner: Parthraj Singh Bhati.
Downstream implementations land in:
  - src/clean.py (Taj) -> data/processed/clean.csv
  - src/split.py & src/preprocess.py (Parth) -> data/splits/
  - src/metrics.py (Satya) -> evaluation metrics
"""

from __future__ import annotations

from pathlib import Path
from typing import Any, Tuple

import pandas as pd

from src.config import CLEAN_CSV, DATA_SPLITS, TARGET_COLUMN, TARGET_KIND


def load_data(path: Path | str | None = None) -> pd.DataFrame:
    """Load the project dataset.

    Returns the cleaned, documented table from ``data/processed/clean.csv``.
    No imputation or scaling happens here — those belong to the preprocessing
    pipeline (src/preprocess.py), which is fitted on the training split only.

    Parameters
    ----------
    path : Path | str | None, optional
        Custom path to cleaned CSV. Defaults to ``src.config.CLEAN_CSV``.

    Returns
    -------
    pd.DataFrame
        Cleaned dataset ready for splitting and pipeline transformation.

    Raises
    ------
    FileNotFoundError
        If ``data/processed/clean.csv`` has not yet been generated by Taj's
        cleaning pipeline (src/clean.py).
    """
    csv_path = Path(path) if path is not None else CLEAN_CSV
    if not csv_path.exists():
        raise FileNotFoundError(
            f"Cleaned dataset not found at '{csv_path}'. "
            "Taj's cleaning pipeline (src/clean.py / 01_cleaning.ipynb) must be "
            "run first to produce data/processed/clean.csv before loading clean data."
        )
    return pd.read_csv(csv_path)


def get_splits(
    splits_dir: Path | str | None = None,
) -> Tuple[Any, Any, Any, Any, Any, Any]:
    """Return the shared, seeded train/validation/test split.

    The actual split implementation will be completed by Parth in ``src/split.py``
    after the cleaned dataset (``data/processed/clean.csv``) is available.

    Returns
    -------
    tuple
        ``(X_train, X_val, X_test, y_train, y_val, y_test)``

    Notes
    -----
    - Split will be performed by site/station ('Area') or time ('Date') if
      metadata permits, otherwise a seeded random split using ``src.config.SEED``.
    - Preprocessing (imputation, scaling, encoding) will be fitted on
      training data only to guarantee zero data leakage.
    - Split indices will be persisted under ``data/splits/`` to guarantee byte-identical
      inputs for Random Forest (Himanshu), XGBoost (Jivit), and Naive Baseline (Satya).
    - The test set must be touched exactly once during final evaluation.

    Raises
    ------
    NotImplementedError
        Raised until Parth implements ``src/split.py`` after Taj's clean data lands.
    """
    raise NotImplementedError(
        "Shared splits are not yet generated. Parth will implement src/split.py "
        "and persist indices to data/splits/ once Taj's clean dataset is merged."
    )


def evaluate(y_true, y_pred) -> dict[str, float]:
    """Evaluate predictions using the project's agreed metrics.

    Final metric implementations will be provided in ``src/metrics.py`` (Satya)
    after the baseline and evaluation protocols are established.

    Parameters
    ----------
    y_true : array-like of shape (n_samples,)
        Ground-truth target values (continuous CCME_Values for regression).
    y_pred : array-like of shape (n_samples,)
        Model predictions.

    Returns
    -------
    dict[str, float]
        Dictionary of metric names mapped to their float values (e.g.,
        {'mae': ..., 'rmse': ..., 'r2': ...}), ready for logging to CSV in reports/.

    Raises
    ------
    NotImplementedError
        Raised until Satya completes the metric functions in ``src/metrics.py``.
    """
    try:
        from src.metrics import regression_metrics
        return regression_metrics(y_true, y_pred)
    except (ImportError, NotImplementedError):
        raise NotImplementedError(
            "Evaluation metrics are not yet implemented. Satya will implement "
            "regression_metrics(y_true, y_pred) [MAE, RMSE, R2] in src/metrics.py."
        )
